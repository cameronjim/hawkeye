	{
		SettingsLabel = NSLOCTEXT("Hawkeye", "PauseSettings", "Settings");
	}
	if (ReplayFlashbacksLabel.IsEmpty())
	{
		ReplayFlashbacksLabel = NSLOCTEXT("Hawkeye", "PauseReplayFlashbacks", "Replay flashbacks");
	}
	if (MarkSafehouseLabel.IsEmpty())
	{
		MarkSafehouseLabel = NSLOCTEXT("Hawkeye", "PauseMarkSafehouse", "Mark nearest safehouse");
	}
	if (MarkChallengeLabel.IsEmpty())
	{
		MarkChallengeLabel = NSLOCTEXT("Hawkeye", "PauseMarkChallenge", "Mark nearest challenge");
	}
	if (PhotoModeLabel.IsEmpty())
	{
		PhotoModeLabel = NSLOCTEXT("Hawkeye", "PausePhotoMode", "Photo mode");
	}
	if (RestartMissionLabel.IsEmpty())
	{
		RestartMissionLabel = NSLOCTEXT("Hawkeye", "PauseRestart", "Restart mission");
	}
	if (QuitToMenuLabel.IsEmpty())
	{
		QuitToMenuLabel = NSLOCTEXT("Hawkeye", "PauseQuitToMenu", "Quit to menu");
	}
